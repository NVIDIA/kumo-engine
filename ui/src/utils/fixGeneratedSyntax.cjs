/**
 * Applies narrowly-scoped fixes to Orval-generated TypeScript.
 */

const fs = require("fs");
const path = require("path");

const GEN_DIR = path.resolve(__dirname, "../gen");
// Scoped to `enabled:` so the !!x collapse is only applied where the value is
// already coerced to boolean.
const ENABLED_GUARD =
    /enabled:\s*([A-Za-z0-9_$]+) !== null &&\s+\1 !== undefined/g;
// Orval widens tuple-valued OpenAPI defaults to number[]. Zod's tuple default
// requires the exact tuple type. Keep the general [0, 0] form from the auth
// schema and the named position tuple form used by graph schemas.
const ZERO_TUPLE_DEFAULT = /(export const \w+Default =\s*\n\s*)\[0, 0\];/g;
const POSITION_TUPLE_DEFAULT =
    /(export const [A-Za-z0-9_$]+PositionDefault\s*=\s*\[[^,\]\n]+,\s*[^\]\n]+\])(?!\s+as \[number, number\]);/g;
const DESCRIBE_STRINGS = [
    /(\.describe\(\s*")((?:[^"\\]|\\.)*)("\s*\))/gs,
    /(\.describe\(\s*')((?:[^'\\]|\\.)*)('\s*\))/gs
];
const ORVAL_BANNER = `/**
 * Generated by orval
 * Do not edit manually.
 */`;
const MISPLACED_ORVAL_BANNER = new RegExp(
    `^(import type \\{[\\s\\S]*?\\n\\} from "@tanstack/react-query";)\\n${ORVAL_BANNER.replace(
        /[.*+?^${}()|[\]\\]/g,
        "\\$&"
    )}`
);

const CREATE_API_KEY_RESPONSE_SCHEMA = `zod
    .object({
        "id": zod.string(),
        "name": zod.string(),
        "type": zod
            .enum(["admin", "user"])
            .describe(
                "Logical API key category used for ownership and UI<slash>admin filtering."
            ),
        "created_time": zod.iso.datetime({ "offset": true, "local": true }),
        "value_preview": zod.string(),
        "value": zod.string()
    })
    .describe("Response returned when an API key is created.")`;

function fixFile(filePath) {
    const original = fs.readFileSync(filePath, "utf8");
    const syntaxFixed = original
        .replaceAll(";,", ";")
        .replace(ENABLED_GUARD, "enabled: !!$1")
        .replace(ZERO_TUPLE_DEFAULT, "$1[0, 0] as [number, number];")
        .replace(POSITION_TUPLE_DEFAULT, "$1 as [number, number];");
    let fixed = DESCRIBE_STRINGS.reduce(
        (content, pattern) =>
            content.replace(
                pattern,
                (_match, prefix, description, suffix) =>
                    `${prefix}${description.replaceAll("\\/", "/")}${suffix}`
            ),
        syntaxFixed
    );
    fixed = fixed.replace(MISPLACED_ORVAL_BANNER, `${ORVAL_BANNER}\n$1`);

    if (filePath.endsWith(path.join("gen", "v0", "schemas", "api-keys.ts"))) {
        fixed = fixed
            .replace(
                /export const CreateApiKeysAdminResponse = zod\s*\.void\(\);/,
                `export const CreateApiKeysAdminResponse = ${CREATE_API_KEY_RESPONSE_SCHEMA};`
            )
            .replace(
                /export const CreateApiKeysResponse = zod\s*\.void\(\);/,
                `export const CreateApiKeysResponse = ${CREATE_API_KEY_RESPONSE_SCHEMA};`
            );
    }

    if (fixed !== original) {
        fs.writeFileSync(filePath, fixed, "utf8");
        console.log(`Fixed: ${path.relative(process.cwd(), filePath)}`);
    }
}

function walk(dir) {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
        const fullPath = path.join(dir, entry.name);
        if (entry.isDirectory()) {
            walk(fullPath);
        } else if (entry.isFile() && entry.name.endsWith(".ts")) {
            fixFile(fullPath);
        }
    }
}

walk(GEN_DIR);
