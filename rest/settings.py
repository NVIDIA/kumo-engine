"""
Configure the REST API app through ENV variables. This is meant for
configuring and running REST API app without making code changes in prod,
pre-prod, staging, as well as devserver.

For hosted deployments, configure environment variables in the deployment
system that manages the ``kumo-rest`` container.

For DEV (make devserver), ENV variables are configured in
rest/devserver/main.py

Upon app startup, "KumoRestSettings" is generated by parse_from_env_vars()
based on the declared "EnvVar"s in this file. To add a new EnvVar, update the
"KumoRestSettings" schema and parse_from_env_vars() accordingly, then set the
desired value in the relevant deployment configuration.

Steps to remove an EnvVar: 1) make the code cleanup to delete the EnvVar and
its references, also remove the env variable for DEV (devserver); 2) merge
the code and wait for new docker image to be built; 3) remove the env var
configuration for {prod, staging, pre-prod}, REMEMBER to update the docker
image build version at the same time.

"""

