"""
Sync MCP server configurations between Claude Code and Codex.

This script reads the master MCP configuration from .agents/mcp-servers.json
and updates both:
- .claude/settings.json (for Claude Code)
- .codex/config.toml (for Codex)

Usage:
    python3 .agents/scripts/sync-mcp.py
"""

import json
import os
import sys
from pathlib import Path


def get_project_root():
    """Get the project root directory."""
    if "CLAUDE_PROJECT_DIR" in os.environ:
        return Path(os.environ["CLAUDE_PROJECT_DIR"])
    # Walk up from script location
    script_dir = Path(__file__).parent
    return script_dir.parent.parent


def load_master_config(project_root: Path) -> dict:
    """Load the master MCP servers configuration."""
    config_file = project_root / ".agents" / "mcp-servers.json"
    if not config_file.exists():
        print(f"Error: Master config not found at {config_file}")
        sys.exit(1)

    with open(config_file) as f:
        return json.load(f)


def update_claude_settings(project_root: Path, master_config: dict):
    """Update .claude/settings.json with MCP permissions."""
    settings_file = project_root / ".claude" / "settings.json"

    # Load existing settings or create new
    if settings_file.exists():
        with open(settings_file) as f:
            settings = json.load(f)
    else:
        settings = {}

    # Ensure permissions structure exists
    if "permissions" not in settings:
        settings["permissions"] = {}
    if "allow" not in settings["permissions"]:
        settings["permissions"]["allow"] = []

    # Get current non-MCP permissions
    current_perms = settings["permissions"]["allow"]
    non_mcp_perms = [p for p in current_perms if not p.startswith("mcp__")]

    # Generate MCP permissions from master config
    mcp_perms = []
    for server_name, server_config in master_config.get("servers", {}).items():
        tools = server_config.get("tools", [])
        for tool in tools:
            perm = f"mcp__{server_name}__{tool}"
            mcp_perms.append(perm)

    # Combine and update
    settings["permissions"]["allow"] = non_mcp_perms + sorted(mcp_perms)

    # Write back
    with open(settings_file, "w") as f:
        json.dump(settings, f, indent=2)
        f.write("\n")

    return len(mcp_perms)


def update_codex_config(project_root: Path, master_config: dict):
    """Update .codex/config.toml with MCP server definitions."""
    codex_dir = project_root / ".codex"
    codex_dir.mkdir(exist_ok=True)
    config_file = codex_dir / "config.toml"

    # Generate TOML content
    lines = [
        "# Codex Configuration",
        "# Auto-generated by sync-mcp.py - do not edit directly",
        "",
        "[agent]",
        'instructions_file = "AGENTS.md"',
        'skills_directory = ".agents/skills"',
        'specialists_directory = ".agents/specialists"',
        "",
    ]

    for server_name, server_config in master_config.get("servers", {}).items():
        lines.append(f"[mcp_servers.{server_name}]")
        lines.append(f'command = "{server_config.get("command", "")}"')

        # Format args as TOML array
        args = server_config.get("args", [])
        args_str = ", ".join(f'"{a}"' for a in args)
        lines.append(f"args = [{args_str}]")

        # Add environment variables if present
        env = server_config.get("env", {})
        if env:
            env_pairs = ", ".join(f'{k} = "{v}"' for k, v in env.items())
            lines.append(f"env = {{ {env_pairs} }}")

        lines.append("")

    with open(config_file, "w") as f:
        f.write("\n".join(lines))

    return len(master_config.get("servers", {}))


def main():
    project_root = get_project_root()

    print("━" * 50)
    print("  MCP Configuration Sync")
    print("━" * 50)

    # Load master config
    master_config = load_master_config(project_root)
    servers = master_config.get("servers", {})
    print(f"\n📋 Master config: {len(servers)} MCP servers defined")
    for name in servers:
        print(f"   - {name}")

    # Update Claude settings
    print("\n🔧 Updating Claude Code settings...")
    claude_count = update_claude_settings(project_root, master_config)
    print(f"   ✅ Added {claude_count} MCP permissions to .claude/settings.json")

    # Update Codex config
    print("\n🔧 Updating Codex config...")
    codex_count = update_codex_config(project_root, master_config)
    print(f"   ✅ Added {codex_count} MCP servers to .codex/config.toml")

    print("\n" + "━" * 50)
    print("✅ MCP configurations synced successfully!")
    print("━" * 50)

    return 0


if __name__ == "__main__":
    sys.exit(main())
