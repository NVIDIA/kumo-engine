# Build a GCP custom image for Kumo single-host.
# Usage: ./packer-build-gcp.sh <kumo_image_tag>
#
# Prerequisites:
#   gcloud auth login                       # user creds — needed for IAP tunnel (SSH proxy)
#   gcloud auth application-default login   # ADC — needed for GCP API calls (Packer/Terraform)
#   gcloud config set project <project-id>
#   aws sso login                           # needed only if images are missing from AR (ECR sync)
#   Docker running locally                  # needed only for ECR → AR sync
#
# This script checks that all required images exist in Artifact Registry before
# starting the Packer build. Any missing images are synced from ECR automatically.
# Set SKIP_IMAGE_SYNC=1 to bypass the check (e.g. images were pushed another way).
set -euo pipefail

if [ $# -ne 1 ]; then
    echo "Usage: $0 <image-tag>"
    echo "  <image-tag>: commit SHA (full 40-char) or version tag (e.g. v2.20.3_gcp)"
    exit 1
fi

KUMO_IMAGE_TAG="$1"
SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"

# IAP tunnel (use_iap=true in Packer) calls `gcloud compute start-iap-tunnel` as
# an SSH ProxyCommand. That uses gcloud user credentials, not ADC. Both are needed.
if ! gcloud auth print-access-token >/dev/null 2>&1; then
    echo "ERROR: gcloud user credentials not found. Run: gcloud auth login"
    exit 1
fi
if ! gcloud auth application-default print-access-token >/dev/null 2>&1; then
    echo "ERROR: GCP ADC not found. Run: gcloud auth application-default login"
    exit 1
fi

# Get GCP project (env var takes precedence over gcloud config)
GCP_PROJECT="${GCP_PROJECT:-$(gcloud config get-value project 2>/dev/null || echo "")}"
if [ -z "$GCP_PROJECT" ]; then
    echo "ERROR: GCP project not set. Either:"
    echo "  export GCP_PROJECT=<project-id>"
    echo "  gcloud config set project <project-id>"
    exit 1
fi

# Build VM variables (affect cost/speed of the Packer build itself):
#   GCP_ZONE, MACHINE_TYPE, BOOT_DISK_SIZE_GB, BOOT_DISK_TYPE
# Launch recommendation variables (written to instance_config.json, not used during build):
#   ACCELERATOR_TYPE, ACCELERATOR_COUNT, LOCAL_SSD_COUNT, LOCAL_SSD_INTERFACE
GCP_ZONE="${GCP_ZONE:-us-west1-b}"
MACHINE_TYPE="${MACHINE_TYPE:-n1-standard-8}"
NVIDIA_DRIVER_VERSION="${NVIDIA_DRIVER_VERSION:-580}"
INSTANCE_NAME="${INSTANCE_NAME:-}"  # empty → kumo-packer-<uuid> generated by Packer
ACCELERATOR_TYPE="${ACCELERATOR_TYPE:-NVIDIA_TESLA_T4}"
ACCELERATOR_COUNT="${ACCELERATOR_COUNT:-1}"
BOOT_DISK_SIZE_GB="${BOOT_DISK_SIZE_GB:-100}"
BOOT_DISK_TYPE="${BOOT_DISK_TYPE:-pd-ssd}"
LOCAL_SSD_COUNT="${LOCAL_SSD_COUNT:-1}"
LOCAL_SSD_INTERFACE="${LOCAL_SSD_INTERFACE:-NVME}"
ARTIFACT_REGISTRY="${ARTIFACT_REGISTRY:-us-west1-docker.pkg.dev}"
ARTIFACT_REGISTRY_REPO="${ARTIFACT_REGISTRY_REPO:-kumo}"
ARTIFACT_REGISTRY_NAMESPACE="${ARTIFACT_REGISTRY_NAMESPACE:-kumo}"

echo "GCP project:       ${GCP_PROJECT}"
echo "GCP zone:          ${GCP_ZONE}"
echo "Machine type:      ${MACHINE_TYPE}"
echo "NVIDIA driver:     ${NVIDIA_DRIVER_VERSION}-server"
echo "Accelerator:       ${ACCELERATOR_COUNT}x ${ACCELERATOR_TYPE}"
echo "Boot disk:         ${BOOT_DISK_SIZE_GB}GB ${BOOT_DISK_TYPE}"
echo "Local SSDs:        ${LOCAL_SSD_COUNT}x 375GB (${LOCAL_SSD_INTERFACE}, attach at launch)"
echo "AR registry:       ${ARTIFACT_REGISTRY}"
echo "AR repo:           ${ARTIFACT_REGISTRY_REPO}"
echo "AR namespace:      ${ARTIFACT_REGISTRY_NAMESPACE}"
echo "Image tag:         ${KUMO_IMAGE_TAG}"

# --- ECR-to-AR image sync ---
# Checks each required image in Artifact Registry. Copies from ECR for any that
# are missing (requires aws sso login). Set SKIP_IMAGE_SYNC=1 to bypass entirely.
SKIP_IMAGE_SYNC="${SKIP_IMAGE_SYNC:-0}"
ECR_REGISTRY="${ECR_REGISTRY:-926922431314.dkr.ecr.us-west-2.amazonaws.com}"
ECR_NAMESPACE="${ECR_NAMESPACE:-kumo}"
AWS_REGION="${AWS_REGION:-us-west-2}"

if [ "${SKIP_IMAGE_SYNC}" != "1" ]; then
    AR_PREFIX="${ARTIFACT_REGISTRY}/${GCP_PROJECT}/${ARTIFACT_REGISTRY_REPO}/${ARTIFACT_REGISTRY_NAMESPACE}"
    ECR_PREFIX="${ECR_REGISTRY}/${ECR_NAMESPACE}"

    # Only the kumo backend/UI images are private and versioned by
    # KUMO_IMAGE_TAG. Every third-party image (prometheus, nginx, jaeger,
    # postgres) is pulled from its upstream public registry during the Packer
    # build, so none of them are synced through Artifact Registry here.
    VERSIONED_IMAGES=("kumo-backend-cpu" "kumo-backend-gpu" "kumo-ui")

    echo ""
    echo "Checking Artifact Registry for required images..."
    missing=()
    for img in "${VERSIONED_IMAGES[@]}"; do
        ar_ref="${AR_PREFIX}/${img}:${KUMO_IMAGE_TAG}"
        if ! gcloud artifacts docker images describe "${ar_ref}" >/dev/null 2>&1; then
            echo "  MISSING: ${ar_ref}"
            missing+=("${img}:${KUMO_IMAGE_TAG}")
        else
            echo "  OK:      ${ar_ref}"
        fi
    done

    if [ ${#missing[@]} -gt 0 ]; then
        echo ""
        echo "Syncing ${#missing[@]} image(s) from ECR → Artifact Registry..."

        if ! aws sts get-caller-identity >/dev/null 2>&1; then
            echo "ERROR: Images missing from AR require sync from ECR, but AWS credentials not found."
            echo "  Run: aws sso login"
            echo "  Or set SKIP_IMAGE_SYNC=1 if images are available by other means."
            exit 1
        fi

        aws ecr get-login-password --region "${AWS_REGION}" \
            | docker login --username AWS --password-stdin "${ECR_REGISTRY}"
        gcloud auth print-access-token \
            | docker login -u oauth2accesstoken --password-stdin "${ARTIFACT_REGISTRY}"

        for ref in "${missing[@]}"; do
            img="${ref%%:*}"
            tag="${ref##*:}"
            src="${ECR_PREFIX}/${img}:${tag}"
            dst="${AR_PREFIX}/${img}:${tag}"
            echo "  ${src} → ${dst}"
            docker pull "${src}"
            docker tag "${src}" "${dst}"
            docker push "${dst}"
            docker rmi "${src}" "${dst}"
        done

        docker logout "${ECR_REGISTRY}" || true
        docker logout "${ARTIFACT_REGISTRY}" || true
        echo "Sync complete."
    else
        echo "All images present in Artifact Registry."
    fi
    echo ""
fi

cd "$SCRIPT_DIR"
packer init kumo-singlehost-gcp.pkr.hcl

exec packer build \
    -var "gcp_project_id=${GCP_PROJECT}" \
    -var "gcp_zone=${GCP_ZONE}" \
    -var "machine_type=${MACHINE_TYPE}" \
    -var "nvidia_driver_version=${NVIDIA_DRIVER_VERSION}" \
    -var "instance_name=${INSTANCE_NAME}" \
    -var "accelerator_type=${ACCELERATOR_TYPE}" \
    -var "accelerator_count=${ACCELERATOR_COUNT}" \
    -var "boot_disk_size_gb=${BOOT_DISK_SIZE_GB}" \
    -var "boot_disk_type=${BOOT_DISK_TYPE}" \
    -var "local_ssd_count=${LOCAL_SSD_COUNT}" \
    -var "local_ssd_interface=${LOCAL_SSD_INTERFACE}" \
    -var "artifact_registry=${ARTIFACT_REGISTRY}" \
    -var "artifact_registry_repo=${ARTIFACT_REGISTRY_REPO}" \
    -var "artifact_registry_namespace=${ARTIFACT_REGISTRY_NAMESPACE}" \
    -var "kumo_image_tag=${KUMO_IMAGE_TAG}" \
    kumo-singlehost-gcp.pkr.hcl
