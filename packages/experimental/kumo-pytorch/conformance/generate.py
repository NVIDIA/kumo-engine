@dataclass(frozen=True)
class GeneratedCase:
    """Everything needed to rerun one case anywhere, as JSON-compatible data."""

    id: str
    seed: int
    scale: Scale
    dimensions: Mapping[str, DimensionValue]
    contract: DataLoaderSpec
    tables: Tables
    requests: tuple[SampleRequest, ...]

    @property
    def path(self) -> tuple[str, ...]:
        return PATHS[str(self.dimensions["schema_shape.path"])]

    def to_dict(self) -> CasePayload:
        return {
            "id": self.id,
            "registry_version": REGISTRY_VERSION,
            "seed": self.seed,
            "scale": self.scale,
            "dimensions": dict(self.dimensions),
            "contract": self.contract.to_dict(),
            "tables": {name: [dict(row) for row in rows] for name, rows in self.tables.items()},
            "anchors": [
                {
                    "sample_id": str(request.sample_id),
                    "entity_id": int(request.entity_id),
                    "as_of_time": int(request.as_of_time),
                }
                for request in self.requests
            ],
        }

    @classmethod
    def from_dict(cls, payload: CasePayload) -> GeneratedCase:
        if payload["registry_version"] != REGISTRY_VERSION:
            raise ValueError(f"case was generated by registry v{payload['registry_version']}")
        contract = DataLoaderSpec.from_dict(payload["contract"])
        contract.validate()
        return cls(
            id=payload["id"],
            seed=payload["seed"],
            scale=payload["scale"],
            dimensions=dict(payload["dimensions"]),
            contract=contract,
            tables={name: [dict(row) for row in rows] for name, rows in payload["tables"].items()},
            requests=tuple(SampleRequest(**anchor) for anchor in payload["anchors"]),
        )


# -- Covering arrays ---------------------------------------------------------


def required_pairs(
    sensitive: Mapping[object, Sequence[str]], domains: Mapping[str, Sequence[DimensionValue]]
) -> set[Pair]:
    """Every value pair of two dimensions that some contract feature is sensitive to together."""

    pairs: set[Pair] = set()
    for names in sensitive.values():
        present = sorted(name for name in names if name in domains)
        for index, first in enumerate(present):
            for second in present[index + 1 :]:
                pairs.update(
                    ((first, a), (second, b)) for a in domains[first] for b in domains[second]
                )
    return pairs


def _pairs_of(row: Mapping[str, DimensionValue]) -> set[Pair]:
    names = sorted(row)
    return {
        ((first, row[first]), (second, row[second]))
        for index, first in enumerate(names)
        for second in names[index + 1 :]
    }


def pairwise(
    domains: Mapping[str, Sequence[DimensionValue]],
    pairs: set[Pair],
    rng: random.Random,
    gaps: Sequence[Region] = (),
) -> list[dict[str, DimensionValue]]:
    """Greedy covering array: each row starts from an uncovered pair, then adds the most.

    No row lies inside a known gap, and pairs inside one aren't required.
    """

    def allowed(row: Mapping[str, DimensionValue]) -> bool:
        return not any(gap.covers(row) for gap in gaps)

    uncovered = {pair for pair in pairs if allowed(dict(pair))}
    rows: list[dict[str, DimensionValue]] = []
    while uncovered:
        (first, a), (second, b) = rng.choice(sorted(uncovered, key=repr))
        row: dict[str, DimensionValue] = {first: a, second: b}
        names = [name for name in sorted(domains) if name not in row]
        rng.shuffle(names)
        for name in names:
            options = [value for value in domains[name] if allowed({**row, name: value})]
            if not options:
                raise ValueError(f"known gaps leave no value of {name} for {row}")
            rng.shuffle(options)
            row[name] = max(
                options,
                key=lambda value: len(_pairs_of({**row, name: value}) & uncovered),
            )
        rows.append(row)
        uncovered -= _pairs_of(row)
    return rows


# -- Schemas and contracts ---------------------------------------------------

PATHS: Mapping[str, tuple[str, ...]] = {
    "depth1_forward": ("user_events",),
    "depth1_reverse": ("event_user",),
    "depth2_static": ("user_accounts", "account_events"),
    "depth2_timed": ("user_accounts", "account_events"),
    "depth1_parent": ("user_events",),
    "depth2_sibling": ("user_links", "link_events"),
    "depth3_static": ("user_accounts", "user_accounts", "user_events"),
}
NUMERIC_COLUMN = {"count_distinct": "category", "mode": "category", "recency": CLOCK}


def schema_for(shape: str) -> DataSchema:
    if shape in SHAPED:
        return shaped_schema(shape)
    users = TableSpec("users", "user_id", {"user_id": DType("int64")}, time_column=NON_TEMPORAL)
    if shape.startswith("depth2"):
        clock = OPENED if shape == "depth2_timed" else NON_TEMPORAL
        return DataSchema(
            tables=(
                users,
                TableSpec(
                    "accounts",
                    "account_id",
                    {
                        "account_id": DType("int64"),
                        "user_id": DType("int64"),
                        OPENED: DType("timestamp", unit="s", timezone="UTC"),
                    },
                    time_column=clock,
                ),
                TableSpec(
                    "events",
                    "event_id",
                    {
                        "event_id": DType("int64"),
                        "account_id": DType("int64"),
                        "amount": DType("float64"),
                        "category": DType("string"),
                        CLOCK: DType("timestamp", unit="s", timezone="UTC"),
                    },
                    time_column=CLOCK,
                ),
            ),
            relations=(
                RelationSpec("user_accounts", "users", "user_id", "accounts", "user_id"),
                RelationSpec("account_events", "accounts", "account_id", "events", "account_id"),
            ),
        )
    events = TableSpec(
        "events",
        "event_id",
        {
            "event_id": DType("int64"),
            "user_id": DType("int64"),
            "amount": DType("float64"),
            "category": DType("string"),
            CLOCK: DType("timestamp", unit="s", timezone="UTC"),
        },
        time_column=CLOCK,
    )
    relation = (
        RelationSpec("user_events", "users", "user_id", "events", "user_id")
        if shape == "depth1_forward"
        else RelationSpec("event_user", "events", "user_id", "users", "user_id")
    )
    return DataSchema(tables=(users, events), relations=(relation,))


def aggregate(
    operation: str, path: tuple[str, ...], *, distinct: bool, start: int | None = None
) -> Aggregate:
    return Aggregate(
        Rows(path, TimeWindow(CLOCK, start, 0), distinct=distinct),
        operation,
        None if operation == "count" else NUMERIC_COLUMN.get(operation, "amount"),
        dtype=DType(
            "string"
            if operation == "mode"
            else "int64"
            if operation in {"count", "count_distinct"}
            else "float64"
        ),
    )


def contract_for(
    schema: DataSchema,
    path: tuple[str, ...],
    *,
    distinct: bool,
    extra: Mapping[str, Aggregate | Compare | Derived] | None = None,
    group_by: bool = False,
) -> DataLoaderSpec:
    values: dict[str, Aggregate | Compare | Derived] = {
        operation: aggregate(operation, path, distinct=distinct)
        for operation in sorted(ALL_REDUCTIONS)
    }
    for window, start in WINDOW_STARTS.items():
        if start is not None:
            values.update(
                {
                    f"{operation}_{window}": aggregate(
                        operation, path, distinct=distinct, start=start
                    )
                    for operation in WINDOWED
                }
            )
    values.update(shaped_values(schema, path, distinct=distinct, group_by=group_by))
    values.update(extra or {})
    numeric = [name for name, value in values.items() if value.dtype.numeric]
    targets = future_targets(path, distinct=distinct)
    return DataLoaderSpec(
        schema,
        SampleSpec(EntitySpec("users", entity_type="user"), entity_values=values, targets=targets),
        BatchSpec(
            inputs={
                "entity": Input(
                    EntitySource(),
                    Fields(
                        fields=tuple(Encode(field=name, encoding=Raw()) for name in numeric),
                        row=Columns(),
                    ),
                    Separate(),
                )
            },
            targets=target_batch(targets),
        ),
    )


def case_contract(
    shape: str,
    dims: Mapping[str, DimensionValue],
    *,
    schema: DataSchema | None = None,
    extra: Mapping[str, Aggregate | Compare | Derived] | None = None,
) -> DataLoaderSpec:
    """The contract a case's dimensions ask for; Raw keeps each value's declared dtype."""

    return contract_for(
        schema or schema_for(shape),
        PATHS[shape],
        distinct=bool(dims["contract.distinct"]),
        extra=extra,
        group_by=dims.get("contract.group_by") == "nested",
    )


# -- Rows --------------------------------------------------------------------


class _Builder:
    """Plant rows so each anchor gets exactly the boundary its dimensions ask for."""

    def __init__(
        self, rng: random.Random, dims: Mapping[str, DimensionValue], size: ScaleSize, base: int
    ):
        self.rng = rng
        self.dims = dims
        self.base = base
        self.times: dict[int, list[int]] = {user: [] for user in range(1, size.users + 1)}

    def free(self, user: int, time: int) -> bool:
        return self.dims["time.ties"] == "tied" or time not in self.times[user]

    def add(self, user: int, time: int) -> None:
        if self.free(user, time):
            self.times[user].append(time)

    def add_before(self, user: int, cutoff: int, count: int, low: int | None = None) -> None:
        while sum(t < cutoff for t in self.times[user]) < count:
            self.add(user, self.rng.randrange(self.base if low is None else low, cutoff - 1))


def generate_case(
    seed: int, index: int, dims: Mapping[str, DimensionValue], scale: Scale
) -> GeneratedCase:
    rng = random.Random(seed * 1_000_003 + index)
    size = SCALES[scale]
    shape = str(dims["schema_shape.path"])
    users = list(range(1, size.users + 1))
    base = BASE_TIME[str(dims["time.range"])]
    grid = tuple(base + offset for offset in CUTOFF_OFFSETS)

    anchors: list[tuple[int, int]] = []
    for position in range(size.anchors):
        user = users[position % len(users)]
        if dims["time.cutoffs"] == "shared":
            cutoff = grid[1]
        else:
            # Entities with several anchors get different cutoffs, every one on the grid.
            cutoff = grid[(position // len(users) + user) % len(grid)]
            cutoff += rng.randrange(0, 50) if position >= len(users) else 0
        anchors.append((user, cutoff))

    builder = _Builder(rng, dims, size, base)
    for user in users:
        for _ in range(rng.randint(0, 2 * size.events_per_user)):
            builder.add(user, rng.randrange(base, base + SPAN))

    empty_user = users[-1] if dims["values.empty_window"] == "present" else None
    single_user = users[-2] if dims["values.single_row"] == "present" else None
    designated = {user for user in (empty_user, single_user) if user is not None}
    offset = {"before": -1, "at": 0, "after": 1}[str(dims["time.cutoff_placement"])]
    for user, cutoff in anchors:
        if offset >= 0 or user not in designated:
            builder.add(user, cutoff + offset)
        if user not in designated:
            # Plant a row at the window start and another immediately before it.
            builder.add(user, cutoff - WINDOW_ROW)
            builder.add(user, cutoff - WINDOW_ROW - 1)
            # The lag window ends at the first and excludes the second.
            builder.add(user, cutoff - LAG)
            builder.add(user, cutoff - LAG + 1)
        for edge in target_edges():
            builder.add(user, cutoff + edge)
    if dims["time.ties"] == "tied":
        for user, cutoff in anchors[:2]:
            builder.times[user].extend([cutoff + offset] * 2)
            # First and last rows of the future windows, tied.
            builder.times[user].extend([cutoff + AHEAD[0] + 1, cutoff + TARGET_SPAN])

    for user, cutoff in sorted(anchors, key=lambda anchor: anchor[1]):
        first = min(c for u, c in anchors if u == user)
        if user in designated:
            if cutoff == first:
                builder.times[user] = [t for t in builder.times[user] if t > cutoff]
                if user == single_user:
                    builder.add(user, rng.randrange(base, cutoff - 1))
            elif cutoff - first > 2:
                builder.add_before(user, cutoff, 2, low=first)
        else:
            builder.add_before(user, cutoff, 2)

    null_rate = str(dims["values.null_rate"])
    if shape in SHAPED:
        tables = shaped_tables(rng, shape, builder.times, base, null_rate=null_rate)
    else:
        tables = _tables(rng, shape, builder.times, base, null_rate=null_rate)
    requests = tuple(
        SampleRequest(f"a{position}", entity_id=user, as_of_time=cutoff)
        for position, (user, cutoff) in enumerate(anchors)
    )
    schema = schema_for(shape)
    if dims.get("schema_shape.parallel_relation") == "present":
        schema = with_parallel_relation(schema)
    contract = case_contract(shape, dims, schema=schema)
    return GeneratedCase(f"s{seed}-c{index}", seed, scale, dict(dims), contract, tables, requests)


def _tables(
    rng: random.Random,
    shape: str,
    times: Mapping[int, Sequence[int]],
    base: int,
    *,
    null_rate: str,
) -> Tables:
    users: list[Row] = [{"user_id": user} for user in times]
    accounts: list[Row] = []
    events: list[Row] = []
    for user, user_times in times.items():
        owned = []
        if shape.startswith("depth2"):
            for _ in range(rng.randint(1, 2)):
                owned.append(len(accounts) + 1)
                accounts.append({"account_id": len(accounts) + 1, "user_id": user, OPENED: base})
        for time in user_times:
            events.append(event_row(rng, len(events) + 1, user, time, owned, null_rate))
    if null_rate == "some" and len(events) > 1:
        events[0].update(amount=None, category=None)
        events[-1].update(amount=1.0, category="a")
    tables: Tables = {"users": users, "events": events}
    if shape.startswith("depth2"):
        tables["accounts"] = accounts
    return tables


def event_row(
    rng: random.Random,
    event_id: int,
    user: int,
    time: int,
    accounts: Sequence[int],
    null_rate: str,
) -> Row:
    null = {"none": 0.0, "some": 0.34, "all": 1.0}[null_rate]
    row: Row = {"event_id": event_id}
    row["account_id" if accounts else "user_id"] = rng.choice(accounts) if accounts else user
    row["amount"] = None if rng.random() < null else float(rng.choice((1, 2, 3, 5, 8)))
    row["category"] = None if rng.random() < null else rng.choice(("a", "b", "c"))
    row[CLOCK] = time
    return row


# -- Functional areas: more shapes, grouped values and targets ---------------

SHAPED = ("depth1_parent", "depth2_sibling", "depth3_static")
SEGMENTS = 3


def shaped_schema(shape: str) -> DataSchema:
    users_columns: dict[str, DType] = {"user_id": INT64}
    tables: list[TableSpec] = []
    relations: list[RelationSpec] = []
    if shape == "depth1_parent":
        users_columns["segment_id"] = INT64
        tables.append(
            TableSpec(
                "segments",
                "segment_id",
                {"segment_id": INT64, "weight": FLOAT64},
                time_column=NON_TEMPORAL,
            )
        )
        relations.append(
            RelationSpec("user_segment", "users", "segment_id", "segments", "segment_id")
        )
    if shape == "depth2_sibling":
        tables.append(
            TableSpec(
                "links",
                "link_id",
                {"link_id": INT64, "user_id": INT64, "event_id": INT64},
                time_column=NON_TEMPORAL,
            )
        )
        relations += [
            RelationSpec("user_links", "users", "user_id", "links", "user_id"),
            RelationSpec("link_events", "links", "event_id", "events", "event_id"),
        ]
    else:
        relations.append(RelationSpec("user_events", "users", "user_id", "events", "user_id"))
    if shape == "depth3_static":
        tables.append(
            TableSpec(
                "accounts",
                "account_id",
                {"account_id": INT64, "user_id": INT64, OPENED: TIMESTAMP},
                time_column=NON_TEMPORAL,
            )
        )
        relations.append(RelationSpec("user_accounts", "users", "user_id", "accounts", "user_id"))
    events = TableSpec(
        "events",
        "event_id",
        {
            "event_id": INT64,
            "user_id": INT64,
            "amount": FLOAT64,
            "category": DType("string"),
            CLOCK: TIMESTAMP,
        },
        time_column=CLOCK,
    )
    users = TableSpec("users", "user_id", users_columns, time_column=NON_TEMPORAL)
    return DataSchema(tables=(users, *tables, events), relations=tuple(relations))


def shaped_tables(
    rng: random.Random,
    shape: str,
    times: Mapping[int, Sequence[int]],
    base: int,
    *,
    null_rate: str,
) -> Tables:
    """Events keep their owner in ``user_id``; the shape decides how a path reaches them."""

    tables = _tables(rng, "depth1_forward", times, base, null_rate=null_rate)
    if shape == "depth1_parent":
        for row in tables["users"]:
            row["segment_id"] = rng.choice((*range(1, SEGMENTS + 1), None))
        tables["users"][0]["segment_id"] = 1
        tables["segments"] = [
            {"segment_id": segment, "weight": float(segment * 10)}
            for segment in range(1, SEGMENTS + 1)
        ]
    if shape == "depth2_sibling":
        tables["links"] = []
        link_events(tables, tables["events"], rng)
    if shape == "depth3_static":
        accounts: list[Row] = []
        for user in times:
            for _ in range(rng.randint(1, 2)):
                accounts.append({"account_id": len(accounts) + 1, "user_id": user, OPENED: base})
        tables["accounts"] = accounts
    return tables


def link_events(tables: Tables, events: Sequence[Row], rng: random.Random) -> None:
    """Link each event to its owner; some twice, so a path reaches them twice."""

    links = tables["links"]
    for index, event in enumerate(events):
        for _ in range(2 if index == 0 or rng.random() < 0.35 else 1):
            links.append(
                {
                    "link_id": len(links) + 1,
                    "user_id": event["user_id"],
                    "event_id": event["event_id"],
                }
            )


def shaped_values(
    schema: DataSchema, path: tuple[str, ...], *, distinct: bool, group_by: bool
) -> dict[str, Aggregate | Compare | Derived]:
    """A static parent's aggregates, a two-key GroupBy and the lag window."""

    values: dict[str, Aggregate | Compare | Derived] = {
        f"{operation}_lag": Aggregate(
            Rows(path, TimeWindow(CLOCK, -WINDOW_ROW, -LAG), distinct=distinct),
            operation,
            None if operation == "count" else "amount",
            dtype=INT64 if operation == "count" else FLOAT64,
        )
        for operation in WINDOWED
    }
    if any(table.name == "segments" for table in schema.tables):
        parent = Rows(("user_segment",), distinct=distinct)
        values.update(
            parent_count=Aggregate(parent, "count", dtype=INT64),
            parent_sum=Aggregate(parent, "sum", "weight", dtype=FLOAT64),
            parent_max=Aggregate(parent, "max", "weight", dtype=FLOAT64),
        )
    if group_by:
        grouped = GroupBy(
            Rows(path, TimeWindow(CLOCK, None, 0), distinct=distinct),
            ("category", "amount"),
            {"rows": Reduce("count"), "total": Reduce("sum", "amount")},
        )
        values.update(
            groups=Aggregate(grouped, "count", dtype=INT64),
            group_rows_max=Aggregate(grouped, "max", "rows", dtype=INT64),
            group_total_sum=Aggregate(grouped, "sum", "total", dtype=FLOAT64),
            group_rows_min=Aggregate(grouped, "min", "rows", dtype=INT64),
        )
    return values


TARGET_FIELDS = ("event_id", "amount")


def future_targets(path: tuple[str, ...], *, distinct: bool) -> dict[str, Aggregate | RowTarget]:
    """Count and sum over (0, TARGET_SPAN] and AHEAD; the first and last row of the former."""

    targets: dict[str, Aggregate | RowTarget] = {}
    for name, (start, stop) in (("next", (0, TARGET_SPAN)), ("ahead", AHEAD)):
        rows = Rows(path, TimeWindow(CLOCK, start, stop), distinct=distinct)
        targets[f"count_{name}"] = Aggregate(rows, "count")
        targets[f"sum_{name}"] = Aggregate(rows, "sum", "amount")
    rows = Rows(path, TimeWindow(CLOCK, 0, TARGET_SPAN), distinct=distinct)
    fields = {name: Field(name) for name in TARGET_FIELDS}
    for selection in ("first", "last"):
        targets[f"{selection}_next"] = RowTarget(rows, fields, selection=selection)
    return targets


def target_batch(
    targets: Mapping[str, Aggregate | RowTarget],
) -> dict[str, LabelTarget | StructuredTarget]:
    return {
        name: LabelTarget(name, Raw())
        if isinstance(target, Aggregate)
        else StructuredTarget(name, tuple(Encode(field, Raw()) for field in target.fields))
        for name, target in targets.items()
    }


def target_edges() -> tuple[int, ...]:
    """Offsets just inside and just outside every target window edge after the cutoff.

    The edge at the cutoff itself is time.cutoff_placement's.
    """

    return tuple(sorted({edge + delta for edge in (TARGET_SPAN, *AHEAD) for delta in (0, 1)}))


def generate_batch(seed: int, engine: str, scale: Scale | None = None) -> list[GeneratedCase]:
    """One seed batch: a pairwise covering array over the sensitive dimensions.

    Bundled dimensions are in every case (every reduction and window). Rotated
    ones give each value once before any repeats. Nothing lies in a blocked region.
    """

    rng = random.Random(seed)
    sensitive = {
        key: [name for name in names if name not in BUNDLED] for key, names in SENSITIVE.items()
    }
    names = sorted({name for names in sensitive.values() for name in names})
    domains = {name: active_values(name, engine) for name in names}
    regions = blocked_regions(engine)
    rows = pairwise(domains, required_pairs(sensitive, domains), rng, regions)
    for name in ROTATED:
        values = active_values(name, engine)
        used: set[DimensionValue] = set()
        for index, row in enumerate(rows):
            rotation = [values[(index + step) % len(values)] for step in range(len(values))]
            allowed = [value for value in rotation if _fits(regions, {**row, name: value})]
            fresh = [value for value in allowed if value not in used]
            # A value confined to a few shapes takes its slot first, or later rows may miss it.
            confined = [v for v in fresh if name == "contract.strategy" and v in STRATEGY_SHAPES]
            row[name] = (confined or fresh or allowed)[0]
            used.add(row[name])
    for index, row in enumerate(rows):
        row.update(engine_settings(engine, index))
    chosen = scale or ENGINE_SCALE[engine]
    return [generate_case(seed, index, row, chosen) for index, row in enumerate(rows)]


def crossed_settings(engine: str) -> list[dict[str, DimensionValue]]:
    """Every combination of the engine's crossed settings (registry.CROSSED); one if none."""

    names = CROSSED.get(engine, ())
    combinations = itertools.product(*(active_values(name, engine) for name in names))
    return [dict(zip(names, values, strict=True)) for values in combinations]


def engine_settings(engine: str, index: int) -> dict[str, DimensionValue]:
    """The ``index``-th combination of the engine's crossed settings."""

    combinations = crossed_settings(engine)
    return combinations[index % len(combinations)]


def with_parallel_relation(schema: DataSchema) -> DataSchema:
    """F2: the first relation declared again under another name, over the same FK column."""

    first = schema.relations[0]
    twin = replace(first, name=f"{first.name}_again")
    return replace(schema, relations=(*schema.relations, twin))


def _fits(regions: Sequence[Region], row: Mapping[str, DimensionValue]) -> bool:
    shapes = STRATEGY_SHAPES.get(str(row.get("contract.strategy")))
    if shapes is not None and row["schema_shape.path"] not in shapes:
        return False
    return not any(region.covers(row) for region in regions)


def delivery_configs(seed: int, engine: str) -> list[dict[str, DimensionValue]]:
    domains = {name: active_values(name, engine) for name in DELIVERY}
    rng = random.Random(seed)
    return pairwise(domains, required_pairs({"delivery": DELIVERY}, domains), rng)


# -- Deliberately invalid and engine-dependent contracts ---------------------


def _with_value(
    case: GeneratedCase, name: str, value: Aggregate | Compare | Derived
) -> DataLoaderSpec:
    shape = str(case.dimensions["schema_shape.path"])
    return case_contract(shape, case.dimensions, schema=case.contract.schema, extra={name: value})


#: Valid by construction unless the name says otherwise; an engine may still refuse.
STRATEGIES: Mapping[str, Callable[[GeneratedCase], DataLoaderSpec]] = {
    "valid": lambda case: case.contract,
    "invalid_unknown_column": lambda case: _with_value(
        case,
        "broken",
        Aggregate(
            Rows(case.path, TimeWindow(CLOCK, None, 0)), "sum", "missing", dtype=DType("float64")
        ),
    ),
    "invalid_unknown_relation": lambda case: _with_value(
        case,
        "broken",
        Aggregate(
            Rows(("no_such_relation",), TimeWindow(CLOCK, None, 0)), "count", dtype=DType("int64")
        ),
    ),
    "window_on_value_column": lambda case: _with_value(
        case,
        "broken",
        Aggregate(Rows(case.path, TimeWindow("amount", None, 0)), "count", dtype=DType("int64")),
    ),
    "row_filter": lambda case: _with_value(
        case,
        "filtered",
        Aggregate(
            Rows(case.path, TimeWindow(CLOCK, None, 0), (RowFilter("amount", "not_null"),)),
            "count",
            dtype=DType("int64"),
        ),
    ),
    "comparison": lambda case: _with_value(
        case,
        "busy",
        Compare(
            aggregate("count", case.path, distinct=True), "greater_than", 1, dtype=DType("bool")
        ),
    ),
    "derived": lambda case: _with_value(
        case, "total_per_row", Derived("divide", ("sum", "count"), dtype=DType("float64"))
    ),
    "timed_intermediate": lambda case: case_contract(
        str(case.dimensions["schema_shape.path"]),
        case.dimensions,
        schema=schema_for("depth2_timed"),
    ),
}
#: Strategies that only make sense for some schema shapes.
STRATEGY_SHAPES: Mapping[str, tuple[str, ...]] = {"timed_intermediate": ("depth2_static",)}


def shifted(case: GeneratedCase, seconds: int) -> GeneratedCase:
    """Every clock value and cutoff moved by ``seconds``."""

    tables = {
        name: [
            {
                key: value + seconds if key in (CLOCK, OPENED) else value
                for key, value in row.items()
            }
            for row in rows
        ]
        for name, rows in case.tables.items()
    }
    requests = tuple(
        replace(request, as_of_time=int(request.as_of_time) + seconds) for request in case.requests
    )
    return replace(case, tables=tables, requests=requests)


def permuted(case: GeneratedCase, rng: random.Random) -> GeneratedCase:
    tables = {name: rng.sample(rows, len(rows)) for name, rows in case.tables.items()}
    return replace(
        case, tables=tables, requests=tuple(rng.sample(case.requests, len(case.requests)))
    )


def entity_cutoffs(requests: Iterable[SampleRequest]) -> dict[int, list[int]]:
    cutoffs: dict[int, list[int]] = {}
    for request in requests:
        cutoffs.setdefault(int(request.entity_id), []).append(int(request.as_of_time))
    return cutoffs


# -- Raw sampling: covering rows for the graph and sequence generators -------


def covering_rows(
    seed: int, engine: str, names: Sequence[str], property_name: str
) -> list[tuple[int, dict[str, DimensionValue]]]:
    """Indexed rows covering every value pair of ``names`` outside blocked regions.

    Every property shares one covering array outside the engine's refusals. A
    known gap blocks only the property that found it: that property drops the
    shared rows inside the gap and adds rows for the pairs they alone covered.
    """

    regions = blocked_regions(engine)
    refusals = tuple(region for region in regions if not isinstance(region, KnownGap))
    gaps = tuple(r for r in regions if isinstance(r, KnownGap) and r.property == property_name)
    domains = {
        name: tuple(
            value
            for value in BY_NAME[name].values
            if not any(set(r.when) == {name} and value in r.when[name] for r in refusals)
        )
        for name in names
    }
    pairs = required_pairs({property_name: names}, domains)
    shared = pairwise(domains, pairs, random.Random(seed), refusals)
    kept = [(i, row) for i, row in enumerate(shared) if not any(g.covers(row) for g in gaps)]
    missing = pairs - set().union(set(), *(_pairs_of(row) for _, row in kept))
    extra = pairwise(domains, missing, random.Random(seed), refusals + gaps) if missing else []
    rows = kept + list(enumerate(extra, len(shared)))
    return [(index, _with_settings(row, engine, index, gaps)) for index, row in rows]


def _with_settings(
    row: Mapping[str, DimensionValue], engine: str, index: int, gaps: Sequence[KnownGap]
) -> dict[str, DimensionValue]:
    """The row with the ``index``-th crossed setting, or the next one outside ``gaps``."""

    combinations = crossed_settings(engine)
    for step in range(len(combinations)):
        settled = {**row, **combinations[(index + step) % len(combinations)]}
        if not any(gap.covers(settled) for gap in gaps):
            return settled
    raise ValueError(f"known gaps leave no engine setting for {dict(row)}")


def case_digest(case: GeneratedCase) -> str:
    """Identifies a case by content, for reusing one engine run across properties."""

    return hashlib.sha256(json.dumps(case.to_dict(), sort_keys=True).encode()).hexdigest()
